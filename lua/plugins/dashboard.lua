local find_files_action = ":lua Snacks.dashboard.pick('files')"
local new_file_action = ":ene | startinsert"
local projects_action = ":lua Snacks.picker.projects()"
local grep_action = ":lua Snacks.dashboard.pick('live_grep')"
local old_files_action = ":lua Snacks.dashboard.pick('oldfiles')"
local config_action = ":lua Snacks.dashboard.pick('files', {cwd = vim.fn.stdpath('config')})"
local restore_session_action = "session"
local quit_action = ":qa"

local my_keys = {
  { icon = " ", key = "f", desc = "Find File", action = find_files_action },
  { icon = " ", key = "n", desc = "New File", action = new_file_action },
  { icon = " ", key = "p", desc = "Projects", action = projects_action },
  { icon = " ", key = "g", desc = "Find Text", action = grep_action },
  { icon = " ", key = "r", desc = "Recent Files", action = old_files_action },
  { icon = " ", key = "c", desc = "Config", action = config_action },
  { icon = " ", key = "s", desc = "Restore Session", section = restore_session_action },
  { icon = " ", key = "q", desc = "Quit", action = quit_action },
}

local function apply_colors()
  vim.cmd("hi! link SnacksDashboardHeader Type")
  vim.cmd("hi! link SnacksDashboardDesc Identifier")
  vim.cmd("hi! link SnacksDashboardKey Special")
  vim.cmd("hi! link SnacksDashboardFooter Identifier")
  vim.cmd("hi! link SnacksDashboardIcon Special")
end

local function dashboard()
  Snacks.dashboard()
end

return {
  {
    "folke/snacks.nvim",
    opts = function(_, opts)
      highlights.on_colorscheme("DashboardHighlights", apply_colors)

      local my_opts = {
        dashboard = {
          preset = { keys = my_keys },
          sections = {
            { header = yoda, padding = 2 },
            { section = "keys", gap = 1, padding = 2 },
            { section = "startup" },
          },
        },
      }
      return vim.tbl_deep_extend("force", opts, my_opts)
    end,
    keys = { { "<leader>od", dashboard, desc = "Dashboard" } },
  },
}
